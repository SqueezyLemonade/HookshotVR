"""vk_vr_slingshot.h: the Fairy Slingshot as the VR hand holds it, and where its pouch and fork are.

The game's slingshot (Weapon_Range_SlingShot) is a bow to the game: its BowParam mounts it on Link's Weapon_L socket (the
left hand) and lets the shot chase the pouch bone (SelfBoneName Ph_Belt). The model: its handle at the origin, the fork's
two arms up +Z (their tips Arm_2_L / Arm_2_R, apart along Y), the pouch (Ph_Belt) behind the fork along +X, so a shot
leaves along -X. The pouch's two straps (Ph_Belt_1_L / _R) run to the fork tips through Ph_String_1..3 on each side.

The VR slingshot is drawn from the game's idle pose for it (Weapon_Pose_Sling, its first frame), held as Link holds it: the
VR left wrist x the game's Weapon_L socket, its mirror image in the right (mirrored across the model's own Y, so it stays a
rotation). Only the drawing hand moves the pouch (vr/items/slingshot/held_slingshot.inc).

Read from your game's files: the model's shape vertex buffer sizes (how its draws are recognised), its palette at rest,
which palette slots are the pouch and each strap, the fork's tips, the pouch's place, and both hands' sockets.
"""
import numpy as np

from bfres_anim import animations
from bow_rest import rest_palette, rotation
from hand_sockets import socket
from hookshot import mirrored
from models import ADULT, CHILD, matrix

OUTPUT = "vk_vr_slingshot.h"
MODEL = "Model/Weapon_Range_SlingShot.Weapon_Range_SlingShot.bfres.zs"
ANIMATIONS = "Model/Weapon_Range_SlingShot_Animation.anim.bfres.zs"
INPUTS = (MODEL, ANIMATIONS, ADULT, CHILD)
POSE = "Weapon_Pose_Sling"
POUCH = ("Ph_Belt", "Ph_Belt_1_L", "Ph_Belt_1_R", "Ph_DekuSeed_1")   # (the pouch and what rides in it: moved as one)


def row(name, m):
    return "inline constexpr float " + name + "[12] = {" + ", ".join("%.9ff" % v for v in m[:3].flat) + "};"


def vec(name, v):
    return "inline constexpr float " + name + "[3] = {" + ", ".join("%.9ff" % x for x in v) + "};"


def slots(name, values):
    return "inline constexpr int16_t %s[%d] = {%s};" % (name, len(values), ", ".join("%d" % v for v in values))


def make(models):
    m = models[MODEL]
    bones = m["bones"]
    by = {b["name"]: b["i"] for b in bones}
    still = animations(models.game.read(ANIMATIONS), [POSE])[POSE]
    pose = {b["name"]: still.bone(b["name"], 0) for b in bones}
    palette = rest_palette(m, pose, relative=False)
    # (each bone's place in the model, posed: a rigid palette slot holds it; a smooth one is that x its inverse bind)
    def place(name):
        s = max(i for i, b in enumerate(m["matrix_to_bone"]) if b == by[name])
        return palette[s] if s >= m["nsmooth"] else palette[s] @ np.linalg.inv(matrix(m["inv_bind"][s]))

    def at(name):   # (a bone not in the palette: its parent's place x its own posed local transform)
        b = bones[by[name]]
        s, r, t = pose[name]
        local = np.eye(4)
        local[:3, :3] = rotation(*(r or b["rot"])[:3]) @ np.diag(s or b["scale"])
        local[:3, 3] = t or b["pos"]
        return (place(bones[b["parent"]]["name"]) @ local)[:3, 3]

    tips = [at("Arm_2_L"), at("Arm_2_R")]
    fork = (tips[0] + tips[1]) / 2
    pouch = place("Ph_Belt")[:3, 3]
    anchors = [place("Ph_Belt_1_L")[:3, 3], place("Ph_Belt_1_R")[:3, 3]]
    # (the axes the placement assumes: refused if a game version moved them. The fork's tips apart along Y and up +Z from
    # the handle, the pouch behind them along +X, each strap's end at its tip)
    assert tips[0][1] < -.03 and tips[1][1] > .03 and abs(tips[0][1] + tips[1][1]) < 1e-3, tips
    assert fork[2] > .1 and abs(fork[0]) < .02, fork
    assert pouch[0] > .05 and abs(pouch[1]) < .02 and abs(pouch[2] - fork[2]) < .1, (pouch, fork)
    for side, tip in zip("LR", tips):
        end = place("Ph_String_3_" + side)[:3, 3]
        assert np.linalg.norm(end - tip) < .01, (side, end, tip)
    pouch_slots = sorted(s for s, b in enumerate(m["matrix_to_bone"]) if bones[b]["name"] in POUCH)
    strap = [sorted(s for s, b in enumerate(m["matrix_to_bone"]) if bones[b]["name"].startswith("Ph_String_") and
                    bones[b]["name"].endswith("_" + side)) for side in "LR"]
    assert len(pouch_slots) == 6 and len(strap[0]) == len(strap[1]) == 3, (pouch_slots, strap)
    out = ["// Generated by vr/tools/generate (slingshot.py) from your game's slingshot model, its idle pose and Link's",
           "// skeletons. Vertex buffer sizes and a few transforms only. Local file: do not commit or share.", "#pragma once",
           "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "/// The slingshot's shapes (its handle and fork, straps, pouch and seed): their vertex buffer sizes",
           "inline constexpr uint64_t sling_shapes[%d] = {%s};" % (len(m["shapes"]), ", ".join(
               "%d" % s["vb0"] for s in m["shapes"])),
           "inline constexpr unsigned sling_matrices = %d;   // (its palette, 48 bytes each)" % len(m["matrix_to_bone"]),
           "/// Its palette in the game's idle pose (%s), in the model's own space (the handle at the origin)" % POSE,
           "inline constexpr float sling_rest[%d][12] = {" % len(palette)]
    out += ["    {" + ",".join("%.7ff" % (0.0 if abs(v) < 5e-8 else v) for v in p[:3].flat) + "}," for p in palette]
    out += ["};",
            "/// The fork's centre (between its tips, where the shot leaves through) and the pouch at rest, in the model",
            vec("sling_fork", fork), vec("sling_pouch", pouch),
            "/// Each side's fork tip and the strap's end on the pouch (left, right), at rest",
            vec("sling_tip_l", tips[0]), vec("sling_tip_r", tips[1]),
            vec("sling_anchor_l", anchors[0]), vec("sling_anchor_r", anchors[1]),
            "/// The palette slots that move with the pouch, and each strap's (left, right)",
            slots("sling_pouch_slots", pouch_slots), slots("sling_strap_l", strap[0]), slots("sling_strap_r", strap[1]),
            "/// Where the slingshot's origin sits in each wrist: the game's Weapon_L socket in the left, its mirror in the right"]
    for n, f in (("adult", ADULT), ("child", CHILD)):
        left = socket(models[f], np.eye(4))
        out += [row("sling_left_" + n, left), row("sling_right_" + n, mirrored(models[f], left, np.diag([1.0, -1, 1, 1])))]
    out.append("} // namespace mkwvk::vr::rig")
    return "\n".join(out) + "\n"
