"""vk_vr_arrows.h: the game's standalone arrows (normal, fire, ice, light), as the held arrow on the VR bow recognises them.

The arrow nocked on the bow is one of these models, one rigid matrix each: the normal arrow is one shape; the elemental
ones add a crystal (fire, ice, light) and a god-ray cone (light), all on that matrix, so moving the matrix onto the VR
string takes their colour, glow and animated material with them. Each elemental model also has an Effect_0 bone: where
the game attaches the arrow's particle effect. Its place on the arrow is kept for the effects (not moved yet).

Read from your game's models: their shapes' vertex buffer sizes (how their draws are recognised) and Effect_0's place.
"""
import numpy as np

from models import matrix

OUTPUT = "vk_vr_arrows.h"
ARROWS = (("normal", "Item_Arrow_Normal.Item_Arrow_Normal"), ("fire", "Item_Arrow_Fire.Item_Arrow_Fire"),
          ("ice", "Item_Arrow_Ice.Item_Arrow_Ice"), ("light", "Item_Arrow_Light.Item_Arrow_Light"))
INPUTS = tuple("Model/%s.bfres.zs" % m for _, m in ARROWS)


def local(bone):
    x, y, z = bone["rot"][:3]
    cx, sx, cy, sy, cz, sz = np.cos(x), np.sin(x), np.cos(y), np.sin(y), np.cos(z), np.sin(z)
    r = np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]) @ np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]) @ \
        np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]])
    m = np.eye(4)
    m[:3, :3], m[:3, 3] = r @ np.diag(bone["scale"]), bone["pos"]
    return m


def model_space(bones, i):
    m = np.eye(4)
    while i >= 0:
        m = local(bones[i]) @ m
        i = bones[i]["parent"]
    return m


def make(models):
    rows, effects = [], []
    for element, (tag, name) in enumerate(ARROWS):
        m = models["Model/%s.bfres.zs" % name]
        assert m["nsmooth"] == 0 and m["nrigid"] == 1, (name, m["nsmooth"], m["nrigid"])
        rows += [(s["vb0"], element, s["name"]) for s in m["shapes"]]
        by = {b["name"]: b["i"] for b in m["bones"]}
        if "Effect_0" in by:
            # (Effect_0 in the rigid matrix's own space: where the effect sits on the arrow as drawn)
            rigid = model_space(m["bones"], m["matrix_to_bone"][0])
            p = (np.linalg.inv(rigid) @ model_space(m["bones"], by["Effect_0"]))[:3, 3]
            effects.append((tag, p))
    assert len({r[0] for r in rows}) == len(rows), "two arrow shapes share a vertex buffer size"
    out = ["// Generated by vr/tools/generate (arrows.py) from your game's arrow models.",
           "// Vertex buffer sizes and one point per arrow only. Local file: do not commit or share.", "#pragma once",
           "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "enum ArrowElement { arrow_normal, arrow_fire, arrow_ice, arrow_light };",
           "/// A shape of a standalone arrow: its vertex buffer size and which arrow it is (all one rigid matrix, 48 bytes)",
           "struct ArrowShape { uint64_t vb0; uint8_t element; };",
           "inline constexpr ArrowShape arrow_shapes[%d] = {" % len(rows)]
    out += ["    {%d, %d},   // %s" % (vb0, element, shape) for vb0, element, shape in rows]
    out += ["};", "/// Where each elemental arrow's effect is attached (Effect_0), in the arrow's own matrix space (m)"]
    out += ["inline constexpr float arrow_effect_%s[3] = {%s};" % (tag, ", ".join("%.6ff" % v for v in p)) for tag, p in effects]
    out += ["} // namespace mkwvk::vr::rig"]
    return "\n".join(out) + "\n"
