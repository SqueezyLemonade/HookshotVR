"""vk_vr_rig_data.h: Link's body regions, arm chains and bind-pose joint positions, for adult and child Link.

Read from Player_Adult and Player_Child's skeletons. For each palette slot: which body region it moves (torso, hips and
legs, head, left arm, right arm). For each arm: the slots of the clavicle, upper arm, forearm, wrist, elbow and wrist
helpers, each finger segment, and the bind-pose positions of the shoulder, elbow, wrist and finger roots.
"""
import numpy as np

from models import ADULT, CHILD, first_palette_slot, matrix

OUTPUT = "vk_vr_rig_data.h"
INPUTS = (ADULT, CHILD)


def model(r, tag):
    B, m2b, ns = r["bones"], r["matrix_to_bone"], r["nsmooth"]
    by = {b["name"]: b["i"] for b in B}
    slot_of = first_palette_slot(r)
    kids = {}
    for b in B:
        kids.setdefault(b["parent"], []).append(b["i"])

    def sub(i):   # a bone and every bone under it
        out = [i]
        for c in kids.get(i, []):
            out += sub(c)
        return out

    def slots(bones):
        return sorted(slot_of[b] for b in bones if b in slot_of)

    def pos(name):   # a bone's bind-pose position, from its (smooth) inverse bind
        s = slot_of[by[name]]
        assert s < ns, name
        return np.linalg.inv(matrix(r["inv_bind"][s]))[:3, 3]

    region = [0] * len(m2b)
    for s, bi in enumerate(m2b):
        chain, i = [], bi
        while i >= 0:
            chain.append(B[i]["name"])
            i = B[i]["parent"]
        region[s] = 2 if "Neck" in chain else 3 if "Clavicle_L" in chain else 4 if "Clavicle_R" in chain else \
            1 if "Waist" in chain else 0
    arms = []
    for side in "LR":
        n = lambda x: x + "_" + side
        up, fo, wr = by[n("Arm_1")], by[n("Arm_2")], by[n("Wrist")]
        fingers = []
        for f in "ABCDE":
            segs = []
            for k in (1, 2, 3):
                b = by[n("Finger_%s_%d" % (f, k))]
                segs.append((slot_of[b], pos(n("Finger_%s_%d" % (f, k))), slots(sub(b))))
            fingers.append(segs)
        arms.append(dict(clav=slot_of[by[n("Clavicle")]], upper=slot_of[up], fore=slot_of[fo], wrist=slot_of[wr],
                         shoulder=pos(n("Arm_1")), elbow_pos=pos(n("Arm_2")), wrist_pos=pos(n("Wrist")),
                         index=pos(n("Finger_B_1")), middle=pos(n("Finger_C_1")), pinky=pos(n("Finger_E_1")),
                         upper_set=slots(set(sub(up)) - set(sub(fo))), fore_set=slots(set(sub(fo)) - set(sub(wr))),
                         hand_set=slots(sub(wr)), elbow=slot_of[by[n("Ph_Elbow")]],
                         assist=(slot_of[by[n("Ph_Wrist_Assist_A")]], slot_of[by[n("Ph_Wrist_Assist_B")]]),
                         fingers=fingers))
    # Joints seen from both sides (child bone, its parent): with the right model, both palette matrices put the joint
    # in the same place, which is how a draw is recognised as adult or child Link
    pairs = []
    for c, p in (("Neck", "Spine_2"), ("Spine_2", "Spine_1"), ("Arm_1_L", "Clavicle_L"), ("Arm_1_R", "Clavicle_R"),
                 ("Arm_2_L", "Arm_1_L"), ("Arm_2_R", "Arm_1_R"), ("Leg_1_L", "Waist"), ("Leg_1_R", "Waist")):
        pairs.append((slot_of[by[c]], slot_of[by[p]], pos(c)))
    return dict(tag=tag, pairs=pairs, slots=len(m2b), neck=slot_of[by["Neck"]], spine=slot_of[by["Spine_1"]],
                waist=slot_of[by["Waist"]], neck_pos=pos("Neck"), spine_pos=pos("Spine_1"), waist_pos=pos("Waist"),
                region=region, arms=arms)


def v(p):
    return "{%.7ff, %.7ff, %.7ff}" % tuple(p)


def lst(xs, n):
    assert len(xs) < n, (len(xs), n)
    return "{" + ", ".join(str(x) for x in xs + [-1] * (n - len(xs))) + "}"


def make(models):
    out = ["// Generated by vr/tools/generate (link_rig.py) from your game's Player_Adult and Player_Child skeletons.",
           "// Bone slots and bind positions only. Local file: do not commit or share.",
           "#pragma once", "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "constexpr int kSlots = 288, kUpper = 16, kFore = 12, kHand = 48, kSeg = 6;",
           "struct Segment { int16_t slot; float joint[3]; int16_t set[kSeg]; };",
           "struct Arm { int16_t clavicle, upper, fore, wrist, elbow, assist[2]; float shoulder[3], elbow_pos[3], wrist_pos[3],",
           "             index[3], middle[3], pinky[3]; int16_t upper_set[kUpper], fore_set[kFore], hand_set[kHand]; Segment finger[5][3]; };",
           "/// region per palette slot: 0 torso, 1 hips and legs, 2 head (hidden), 3 left arm, 4 right arm",
           "struct Pair { int16_t child, parent; float joint[3]; };",
           "struct Model { const char* name; int slots; int16_t neck, spine, waist; float neck_pos[3], spine_pos[3], waist_pos[3];",
           "               uint8_t region[kSlots]; Arm arm[2]; Pair pairs[8]; };"]
    for m in (model(models[ADULT], "adult"), model(models[CHILD], "child")):
        assert m["slots"] <= 288, m["slots"]
        arms = []
        for a in m["arms"]:
            fing = ",\n      ".join("{" + ", ".join("{%d, %s, %s}" % (s, v(p), lst(st, 6)) for s, p, st in segs) + "}"
                                    for segs in a["fingers"])
            arms.append("    {%d, %d, %d, %d, %d, {%d, %d}, %s, %s, %s,\n     %s, %s, %s,\n     %s,\n     %s,\n     %s,\n     {%s}}" % (
                a["clav"], a["upper"], a["fore"], a["wrist"], a["elbow"], a["assist"][0], a["assist"][1],
                v(a["shoulder"]), v(a["elbow_pos"]), v(a["wrist_pos"]), v(a["index"]), v(a["middle"]), v(a["pinky"]),
                lst(a["upper_set"], 16), lst(a["fore_set"], 12), lst(a["hand_set"], 48), fing))
        pairs = ", ".join("{%d, %d, %s}" % (c, p, v(j)) for c, p, j in m["pairs"])
        out.append("inline constexpr Model %s = {\n    \"%s\", %d, %d, %d, %d, %s, %s, %s,\n    {%s},\n    {\n%s},\n    {%s}};" % (
            m["tag"], m["tag"], m["slots"], m["neck"], m["spine"], m["waist"], v(m["neck_pos"]), v(m["spine_pos"]),
            v(m["waist_pos"]), ",".join(str(x) for x in m["region"]), ",\n".join(arms), pairs))
    out.append("} // namespace mkwvk::vr::rig")
    return "\n".join(out) + "\n"
