"""The VR menu's frame (vr/menu/vr_menu.inc): the user's own art, assets/vr/panel_frame.png (a 9-slice, 215 150 226 150 source
pixels), as a header of the build's own: its straight RGBA pixels, zstd-packed (the renderer unpacks them with third_party/zbic),
in a string. Not the game's: the one generator here that reads no game file. Without the picture, the header says so and the
menu draws a plain copper frame instead.

    python panel_frame.py <output folder>

The header starts with the picture's sha256: an unchanged picture is not packed again (packing takes a few seconds).
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SOURCE = os.path.join(REPO, "assets", "vr", "panel_frame.png")
OUTPUT = "vk_vr_panel_frame.h"


def literal(data):
    """bytes as C string pieces: printable ASCII as itself, the rest as three-digit octal escapes (never run together)"""
    out, line = [], []
    width = 0
    for b in data:
        if 32 <= b < 127 and b not in (34, 92, 63):   # (not ", \ or ?: no escape, no trigraph)
            piece = chr(b)
        else:
            piece = "\\%03o" % b
        line.append(piece)
        width += len(piece)
        if width >= 120:
            out.append('"%s"' % "".join(line))
            line, width = [], 0
    if line:
        out.append('"%s"' % "".join(line))
    return "\n".join(out)


def header(png_path=SOURCE):
    if not os.path.isfile(png_path):
        return "// generated by vr/tools/generate/panel_frame.py: no assets/vr/panel_frame.png (a drawn frame instead)\n" \
               "#pragma once\n"
    data = open(png_path, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    sys.path.insert(0, os.path.join(REPO, "nx2"))
    try:
        import logo_rgba   # (its PNG decoder)
    finally:
        sys.path.pop(0)
    import zstandard
    w, h, px = logo_rgba.decode(data)
    packed = zstandard.ZstdCompressor(level=19).compress(px)
    return "\n".join([
        "// sha256 %s" % digest,
        "// generated by vr/tools/generate/panel_frame.py from assets/vr/panel_frame.png (the VR menu's frame): do not edit",
        "#pragma once",
        "#define VR_PANEL_FRAME 1",
        "static const unsigned vr_panel_frame_w = %d, vr_panel_frame_h = %d;" % (w, h),
        "static const char vr_panel_frame_zst[] =",
        literal(packed) + ";",
        ""])


def write(out_dir, png_path=SOURCE):
    """Writes the header into out_dir when it changed; True when it did"""
    path = os.path.join(out_dir, OUTPUT)
    try:
        with open(path, encoding="utf-8") as f:
            first = f.readline()
    except OSError:
        first = ""
    if os.path.isfile(png_path):
        if first == "// sha256 %s\n" % hashlib.sha256(open(png_path, "rb").read()).hexdigest():
            return False
    elif first.startswith("// generated by vr/tools/generate/panel_frame.py: no "):
        return False
    text = header(png_path)
    os.makedirs(out_dir, exist_ok=True)
    with open(path + ".new", "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(path + ".new", path)
    return True


if __name__ == "__main__":
    print("panel_frame: %s" % ("written" if write(sys.argv[1]) else "unchanged"))
