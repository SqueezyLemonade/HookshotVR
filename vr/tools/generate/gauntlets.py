"""vk_vr_armor_bind.h: how the Silver and Golden Gauntlets sit on adult Link's bind pose.

The gauntlets are a separate skinned model with their own 48-matrix palette. Each of their palette slots follows the
body bone of the same name; the six gauntlet-only bones (Ph_Gauntlet_*) follow the nearest ancestor that the body has.
Per slot this writes (body bind) x (gauntlet inverse bind), used when the gauntlets' own upload is not usable. The
values are the Golden Gauntlets'; the Silver Gauntlets' differ by under 0.000001 (the generator checks that).
"""
import numpy as np

from models import ADULT, GOLDEN_GAUNTLETS, SILVER_GAUNTLETS, first_palette_slot, matrix

OUTPUT = "vk_vr_armor_bind.h"
INPUTS = (ADULT, SILVER_GAUNTLETS, GOLDEN_GAUNTLETS)


def body_slots(body, armor):
    """For each gauntlet palette slot, the adult body palette slot it follows"""
    by_name = {body["bones"][b]["name"]: s for b, s in first_palette_slot(body).items()}
    out = []
    for i in range(armor["nsmooth"]):
        b = armor["matrix_to_bone"][i]
        while armor["bones"][b]["name"] not in by_name:
            b = armor["bones"][b]["parent"]
            assert b >= 0, "a gauntlet bone with no body ancestor"
        slot = by_name[armor["bones"][b]["name"]]
        assert slot < body["nsmooth"]
        out.append(slot)
    return out


def corrections(body, armor):
    return [np.linalg.inv(matrix(body["inv_bind"][slot])) @ matrix(armor["inv_bind"][i])
            for i, slot in enumerate(body_slots(body, armor))]


def make(models):
    body, silver, gold = models[ADULT], models[SILVER_GAUNTLETS], models[GOLDEN_GAUNTLETS]
    rows = corrections(body, gold)
    assert len(rows) == 48, len(rows)
    assert body_slots(body, silver) == body_slots(body, gold)
    assert all(np.allclose(a, b, atol=1e-6) for a, b in zip(rows, corrections(body, silver))), "silver and gold differ"
    out = ["// Generated by vr/tools/generate (gauntlets.py): body bind x gauntlet inverse bind, from your game's models.",
           "// Local file: do not commit or share.",
           "#pragma once", "namespace mkwvk::vr::rig {", "inline constexpr float armor_bind[48][12] = {"]
    for m in rows:
        out.append("    {" + ",".join(f"{v:.9f}f" for v in m[:3].flat) + "},")
    out += ["};", "} // namespace mkwvk::vr::rig"]
    return "\n".join(out) + "\n"
