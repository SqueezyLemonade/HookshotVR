"""vk_vr_bomb_flower.h: a Bomb Flower's fruit as a VR hand holds it (vr/items/bomb/bomb_host.c, through the renderer's
flower_shape in vr/items/gear/equipment_skin.inc).

The fruit is the game's own actor (Obj_BombFlower_A_01, _A_04, the Death Mountain rock's fruit), drawn with the model
Obj_BombFlower_A_01: a body and a fuse. Its plant, the leaves, is another actor and another model (Obj_BombFlower_A_03).
The renderer leaves the fruit's draws alone: its body is a rigid shape on Skl_Root, drawn without the palette the renderer
can change, so moving or sizing the palette moved only the fuse (headset, 19 Nov: the stem floated off the fruit). The
game side places the fruit itself against the palm by these sizes, and the fingers rest on it (arms_and_pose.inc).

Read from your game's files: the fruit model's shape vertex buffer sizes and palette size, and its body's centre (above the
actor's origin) and radius from its vertices.
"""
import numpy as np

from arrows import model_space
from bottle import positions

OUTPUT = "vk_vr_bomb_flower.h"
MODEL = "Obj_BombFlower_A_01"
INPUTS = ("Model/Obj_BombFlower_A.%s.bfres.zs" % MODEL,)


def make(models):
    rel = INPUTS[0]
    m = models[rel]
    palette = m["nsmooth"] + m["nrigid"]
    body = next(s["name"] for s in m["shapes"] if s["name"].startswith("Body_"))
    p = positions(models.game.read(rel), body)
    lo, hi = p.min(axis=0), p.max(axis=0)
    half = (hi - lo) / 2
    # (the body is a rigid shape on Skl_Root, its vertices in that bone's space: its centre in the model is the bone's rest
    # place plus its own centre. The model's origin is the actor's, so this is how high the fruit's middle is above it)
    by = {b["name"]: b["i"] for b in m["bones"]}
    centre = model_space(m["bones"], by["Skl_Root"])[:3, 3] + (lo + hi) / 2
    assert 0.1 < half.min() and half.max() < 0.6, "the fruit's body is not the size it was (m): %s" % half
    assert 0.05 < centre[1] < 0.6, "the fruit's body is no longer above its origin (m): %s" % centre
    out = ["// Generated by vr/tools/generate (bomb_flower.py) from your game's Bomb Flower model.",
           "// Vertex buffer sizes and a few sizes only. Local file: do not commit or share.", "#pragma once",
           "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "/// A Bomb Flower fruit's draws (body and fuse): their vertex buffer sizes, and the palette's size (matrices)",
           "inline constexpr uint64_t flower_shapes[%d] = {%s};" % (len(m["shapes"]), ", ".join(str(s["vb0"]) for s in m["shapes"])),
           "inline constexpr uint32_t flower_matrices = %d;" % palette,
           "/// The fruit's body in the model (m): its centre (above the actor's origin) and its radius",
           "inline constexpr float flower_centre[3] = {%.4ff, %.4ff, %.4ff};" % tuple(centre),
           "inline constexpr float flower_radius = %.4ff;" % float(half.mean()),
           "} // namespace mkwvk::vr::rig"]
    return "\n".join(out) + "\n"
