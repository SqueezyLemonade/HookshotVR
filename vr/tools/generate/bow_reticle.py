"""vk_vr_bow_art.h: the bow's aiming reticle masks, from the game's own UI textures.

The four BowPointer textures of Common.bntx are single-channel BC4 images stored in the Switch's block-linear layout.
This decodes them to plain 8-bit masks. The swizzle matches Hookshot's gpu/vk/vk_texture.cpp block-linear addressing.
Can also save a PNG preview for checking: python bow_reticle.py <romfs> preview.png
"""
import struct
import sys

from models import COMMON_TEXTURES

OUTPUT = "vk_vr_bow_art.h"
INPUTS = (COMMON_TEXTURES,)
NAMES = ("BowPointer_00", "BowPointerSh_00", "BowPointerTen_00", "BowPointerTenSh_00")
BC4 = 0x1d01   # (the texture format these masks use; any other is refused)


def textures(d):
    """(name, offset of its BRTI texture header) for every texture in a BNTX file"""
    p = 0
    while True:
        p = d.find(b"BRTI", p)
        if p < 0:
            return
        namep = struct.unpack_from("<Q", d, p + 0x60)[0]
        length = struct.unpack_from("<H", d, namep)[0]
        yield d[namep + 2:namep + 2 + length].decode(), p
        p += 4


def extract(d):
    out = {}
    for name, p in textures(d):
        if name in NAMES:
            fmt = struct.unpack_from("<I", d, p + 0x1c)[0]
            assert fmt == BC4, (name, hex(fmt))
            w, h = struct.unpack_from("<II", d, p + 0x24)
            th = struct.unpack_from("<I", d, p + 0x34)[0] & 7   # (block height, as a power of two)
            table = struct.unpack_from("<Q", d, p + 0x70)[0]
            start = struct.unpack_from("<Q", d, table)[0]
            blocks = (w + 3) // 4
            gobs = (blocks * 8 + 63) // 64
            alpha = bytearray(w * h)

            def byte(x, y):
                gob = ((x & 63) >> 5) * 256 + ((y & 7) >> 2) * 128 + ((x & 31) >> 4) * 64 + ((y >> 1) & 1) * 32 + \
                      (y & 1) * 16 + (x & 15)
                offset = (y >> (3 + th)) * gobs * (512 << th) + (x >> 6) * (512 << th) + \
                         ((y >> 3) & ((1 << th) - 1)) * 512 + gob
                return d[start + offset]
            for by in range((h + 3) // 4):
                for bx in range(blocks):
                    block = bytes(byte(bx * 8 + i, by) for i in range(8))
                    a, b = block[:2]
                    values = [a, b] + ([(a * (7 - i) + b * i) // 7 for i in range(1, 7)] if a > b else
                                       [(a * (5 - i) + b * i) // 5 for i in range(1, 5)] + [0, 255])
                    bits = int.from_bytes(block[2:], "little")
                    for k in range(16):
                        x, y = bx * 4 + k % 4, by * 4 + k // 4
                        if x < w and y < h:
                            alpha[y * w + x] = values[(bits >> (3 * k)) & 7]
            out[name] = (w, h, alpha)
    assert sorted(out) == sorted(NAMES), sorted(out)
    return {n: out[n] for n in NAMES}


def make(models):
    masks = extract(models.game.read(COMMON_TEXTURES))
    out = ["// Generated by vr/tools/generate (bow_reticle.py) from your game's Common.bntx.",
           "// Local file: do not commit or share.", "#pragma once", "#include <cstdint>", "namespace mkwvk::vr::art {"]
    for name, (w, h, a) in masks.items():
        out.append(f"inline constexpr uint8_t {name}[{h}][{w}] = {{")
        out += ["{" + ",".join(map(str, a[y * w:(y + 1) * w])) + "}," for y in range(h)]
        out.append("};")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    from game_files import GameFiles
    from PIL import Image
    masks = extract(GameFiles(sys.argv[1]).read(COMMON_TEXTURES))
    image = Image.new("RGB", (4 * 64, 128), (35, 35, 35))
    for j, (name, (w, h, a)) in enumerate(masks.items()):
        mask = Image.frombytes("L", (w, h), bytes(a)).resize((w * 2, h * 2))
        image.paste((255, 255, 255), (j * 64, 0, j * 64 + w * 2, h * 2), mask)
    image.save(sys.argv[2])
