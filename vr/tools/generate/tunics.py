"""vk_vr_tunic_rig.h: how the Goron and Zora Tunics attach to adult Link.

The tunics are separate skinned models animated with Link, with their own palettes. Per tunic palette slot:
  body    adult Link's palette slot of the same bone, or -1
  parent  the nearest ancestor bone that is also in the tunic palette (its slot), or -1: an anchor for bones the body
          does not skin (cloth keeps its own motion relative to the anchor)
  bind    inverse(adult inverse bind) x tunic inverse bind, the bind-space fallback (VR body slot x bind = tunic slot)
  joint   the bone's bind-pose position in each model, to pair a tunic upload with the same frame's body upload
Also each tunic's vertex buffer sizes, which is how its draws are recognised.
"""
import numpy as np

from models import ADULT, GORON_TUNIC, ZORA_TUNIC, matrix

OUTPUT = "vk_vr_tunic_rig.h"
INPUTS = (ADULT, GORON_TUNIC, ZORA_TUNIC)
MATCH = ("Arm_2_L", "Arm_2_R", "Wrist_L", "Wrist_R", "Spine_2", "Neck")   # (the joints used for pairing)


def tables(adult, tunic):
    apal = {adult["bones"][b]["name"]: s for s, b in enumerate(adult["matrix_to_bone"])}
    tslot = {b: s for s, b in enumerate(tunic["matrix_to_bone"])}
    out = []
    for s, bi in enumerate(tunic["matrix_to_bone"]):
        bone = tunic["bones"][bi]
        a = apal.get(bone["name"], -1)
        p, parent = bone["parent"], -1
        while p >= 0:
            if p in tslot:
                parent = tslot[p]
                break
            p = tunic["bones"][p]["parent"]
        ib_t = matrix(tunic["inv_bind"][s])
        smooth = 0 <= a < adult["nsmooth"]
        bind = np.linalg.inv(matrix(adult["inv_bind"][a])) @ ib_t if smooth else np.eye(4)
        joint_t = np.linalg.inv(ib_t)[:3, 3]
        joint_a = np.linalg.inv(matrix(adult["inv_bind"][a]))[:3, 3] if smooth else joint_t
        out.append(dict(name=bone["name"], body=a, parent=parent, bind=bind[:3].ravel(), joint_t=joint_t, joint_a=joint_a))
    return out


def emit(name, tunic, rows):
    vb0 = sorted({s["vb0"] for s in tunic["shapes"]})
    match = [i for i, r in enumerate(rows) if r["name"] in MATCH and r["body"] >= 0]
    lit = lambda x: (lambda t: t if any(ch in t for ch in ".en") else t + ".0")("%.9g" % (0.0 if abs(x) < 1e-12 else x))
    f = lambda v: ",".join(lit(x) + "f" for x in v)
    lines = ["inline constexpr TunicSlot %s_slots[%d] = {" % (name, len(rows))]
    for r in rows:
        lines.append("    {%d, %d, {%s}},   // %s" % (r["body"], r["parent"], f(r["bind"]), r["name"]))
    lines.append("};")
    lines.append("inline constexpr TunicJoint %s_joints[%d] = {" % (name, len(match)))
    for i in match:
        r = rows[i]
        lines.append("    {%d, %d, {%s}, {%s}},   // %s" % (i, r["body"], f(r["joint_t"]), f(r["joint_a"]), r["name"]))
    lines.append("};")
    lines.append("inline constexpr uint64_t %s_vb0[%d] = {%s};" % (name, len(vb0), ", ".join(map(str, vb0))))
    lines.append("inline constexpr Tunic %s{\"%s\", %d, %s_slots, %d, %s_joints, %d, %s_vb0};" %
                 (name, name, len(rows), name, len(match), name, len(vb0), name))
    return lines


def make(models):
    adult = models[ADULT]
    lines = ["// Generated by vr/tools/generate (tunics.py) from your game's Player_Adult and Goron/Zora tunic models.",
             "// Bone names, palette slots and bind-space corrections only. Local file: do not commit or share.",
             "#pragma once", "#include <cstdint>", "", "namespace mkwvk::vr::rig {",
             "struct TunicSlot { int16_t body, parent; float bind[12]; };",
             "struct TunicJoint { int16_t slot, body; float tunic[3], adult[3]; };",
             "struct Tunic { const char* name; int slots; const TunicSlot* slot; int joints; const TunicJoint* joint; int shapes;",
             "               const uint64_t* vb0; };", ""]
    for name, rel in (("goron", GORON_TUNIC), ("zora", ZORA_TUNIC)):
        tunic = models[rel]
        assert tunic["nrigid"] == 0, name
        lines += emit(name, tunic, tables(adult, tunic)) + [""]
    lines.append("} // namespace mkwvk::vr::rig")
    return "\n".join(lines) + "\n"
