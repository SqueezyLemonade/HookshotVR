"""vk_vr_bottle.h: the bottles as a VR hand holds them (vr/items/bottle/held_bottle.inc).

The held bottle is the game's own actor, Weapon_Bottle or Weapon_Bottle_<content>, and its model shows the contents: the
empty bottle and Blue Fire (Item_Bottle), a bug, a fish, a fairy, a Poe or Big Poe (one model, coloured), a potion (one
model, coloured), milk, half milk, Ruto's Letter. Each model's bottle is the same glass: its mouth up +Z, the cork (shape
Cap) in the neck. The renderer recognises a held bottle's draws by their vertex buffer sizes and moves them all by one
change, from where the game draws the model to the VR hand.

Read from your game's files: each model's shape vertex buffer sizes, its palette size, which palette slot is its root
(Skl_Root, a rigid matrix: the model's place in a draw = that matrix x the root's rest place inverted), and the glass's
size from its vertices (the mouth, the cork, the widest radius).
"""
import struct

import numpy as np

from arrows import model_space

OUTPUT = "vk_vr_bottle.h"
MODELS = ("Item_Bottle", "Item_Bottle_Bug", "Item_Bottle_Fish", "Item_Bottle_Fairy", "Item_Bottle_Poe",
          "Item_Bottle_RedPotion", "Item_Bottle_Milk", "Item_Bottle_HalfMilk", "Item_Bottle_Letter")
INPUTS = tuple("Model/%s.%s.bfres.zs" % (n, n) for n in MODELS)


def positions(data, shape_name):
    """one shape's vertex positions (the first attribute, half floats x4, as every bottle model stores it)"""
    u64 = lambda o: struct.unpack_from("<Q", data, o)[0]
    pool = u64(u64(0xb0) + 8)   # (the file's buffer info: where the vertex data starts)
    i = data.find(b"FSHP")
    while i >= 0:
        n = struct.unpack_from("<H", data, u64(i + 8))[0]
        if data[u64(i + 8) + 2:u64(i + 8) + 2 + n].decode() == shape_name:
            vtx = u64(i + 0x10)
            first = u64(vtx + 8)
            fmt = struct.unpack_from(">I", data, first + 8)[0] >> 16
            assert fmt == 0x515, hex(fmt)   # (half x4: a game version that stores them otherwise needs a reader here)
            offset, count = struct.unpack_from("<I", data, vtx + 0x48)[0], struct.unpack_from("<I", data, vtx + 0x50)[0]
            stride = struct.unpack_from("<I", data, u64(vtx + 0x38))[0]
            return np.array([struct.unpack_from("<4e", data, pool + offset + stride * k)[:3] for k in range(count)])
        i = data.find(b"FSHP", i + 4)
    raise KeyError(shape_name)


def make(models):
    rows, seen = [], set()
    glass = cork = None
    for index, (name, rel) in enumerate(zip(MODELS, INPUTS)):
        m = models[rel]
        by = {b["name"]: b["i"] for b in m["bones"]}
        palette = m["nsmooth"] + m["nrigid"]
        root = m["matrix_to_bone"].index(by["Skl_Root"])
        assert root >= m["nsmooth"], (name, root)   # (a rigid slot: its matrix is the root bone's own place)
        for s in m["shapes"]:
            if (s["vb0"], palette) not in seen:
                seen.add((s["vb0"], palette))
                rows.append((s["vb0"], palette, root, index, s["name"].startswith("Cap_")))
        if name == "Item_Bottle":
            data = models.game.read(rel)
            front = next(s["name"] for s in m["shapes"] if s["name"].startswith("Bottle_Front"))
            glass = positions(data, front)
            cork = positions(data, next(s["name"] for s in m["shapes"] if s["name"].startswith("Cap_")))
            rest = model_space(m["bones"], by["Skl_Root"])
    assert glass[:, 2].max() > .05 and glass[:, 2].min() < -.05, "the bottle's mouth is no longer up +Z"
    radius = float(np.hypot(glass[:, 0], glass[:, 1]).max())
    out = ["// Generated by vr/tools/generate (bottle.py) from your game's bottle models.",
           "// Vertex buffer sizes and a few sizes only. Local file: do not commit or share.", "#pragma once",
           "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "/// A held bottle's draws: vertex buffer size, palette size (matrices), the root's palette slot, which model",
           "/// (0 empty / Blue Fire, 1 bug, 2 fish, 3 fairy, 4 Poe, 5 potion, 6 milk, 7 half milk, 8 letter), and whether it is the cork",
           "struct BottleShape { uint64_t vb0; uint32_t matrices; uint32_t root_slot; uint32_t model; bool cork; };",
           "inline constexpr BottleShape bottle_shapes[%d] = {" % len(rows)]
    out += ["    {%d, %d, %d, %d, %s}," % (v, p, r, i, "true" if c else "false") for v, p, r, i, c in rows]
    out += ["};",
            "/// The root's rest place in the model (the same in every bottle model): a draw's root matrix = the model's place x this",
            "inline constexpr float bottle_root[12] = {" + ", ".join("%.9ff" % v for v in rest[:3].flat) + "};",
            "/// The glass, in the model (m): its bottom and its mouth along Z, its widest radius; the cork's bottom and top",
            "inline constexpr float bottle_bottom = %.4ff, bottle_mouth = %.4ff, bottle_radius = %.4ff;" % (
                glass[:, 2].min(), glass[:, 2].max(), radius),
            "inline constexpr float bottle_cork_bottom = %.4ff, bottle_cork_top = %.4ff;" % (cork[:, 2].min(), cork[:, 2].max()),
            "} // namespace mkwvk::vr::rig"]
    return "\n".join(out) + "\n"
