"""vk_vr_hookshot.h: the hookshot and longshot as the VR hand holds them.

The held hookshot is one model (Item_Hookshot_Body, both items: the longshot shows its own body and hook shapes), 13 rigid
matrices, its barrel along -X (the tips at -0.335 / -0.49 m), its upper claw toward -Y (the handle hangs toward +Y) and
its right claw toward +Z. The game mounts its origin on Link's left hand socket (HookshotParam BowEquippedBoneName
Weapon_L): the VR left hand holds it exactly so. The right hand holds its mirror image: Link's wrists mirror each other across his model's x = 0 (asserted), so
the right socket is the left one mirrored, the model mirrored across its own left-right (z) to stay a rotation.

Read from your game's files: the model's shape vertex buffer sizes (how its draws are recognised), its first palette
matrix's rest place in the model (to find the model's origin in a draw), and both hands' sockets.
"""
import numpy as np

from arrows import model_space
from hand_sockets import socket
from models import ADULT, CHILD, matrix

OUTPUT = "vk_vr_hookshot.h"
BODY = "Model/Item_Hookshot.Item_Hookshot_Body.bfres.zs"
CHAIN = "Model/Item_Hookshot.Item_Hookshot_Chain.bfres.zs"
INPUTS = (BODY, CHAIN, ADULT, CHILD)


def row(name, m):
    return "inline constexpr float " + name + "[12] = {" + ", ".join("%.9ff" % v for v in m[:3].flat) + "};"


def mirrored(body, left, own=np.diag([1.0, 1, -1, 1])):
    """the right wrist's socket that holds the model as the mirror image of the left's. The sockets follow the wrists' skin
    matrices (world x inverse bind); with Link's skeleton mirrored across x = 0 (asserted: the right wrist's bind is the
    left's mirrored, up to a turn of its own frame) a right skin matrix is the left's mirrored on both sides, so the
    mirrored hold is mirror x left socket x the model mirrored across its own left-right axis (own: z for the hookshot,
    y for the slingshot). (A first build put the turn in too: the right hand's hookshot sat a metre away, headset test
    17 Nov.)"""
    def bind(name):
        i = next(b["i"] for b in body["bones"] if b["name"] == name)
        return np.linalg.inv(matrix(body["inv_bind"][body["matrix_to_bone"].index(i)]))
    mx = np.diag([-1.0, 1, 1, 1])
    c = np.linalg.inv(bind("Wrist_L")) @ mx @ bind("Wrist_R")
    assert np.allclose(c[:3, :3] @ c[:3, :3].T, np.eye(3), atol=1e-4) and np.allclose(c[:3, 3], 0, atol=1e-3), c
    right = mx @ left @ own
    assert np.allclose(right[:3, :3].T @ right[:3, :3], np.eye(3), atol=1e-4) and np.linalg.det(right[:3, :3]) > 0, right
    return right


def make(models):
    m = models[BODY]
    assert m["nsmooth"] == 0, m["nsmooth"]
    bones = m["bones"]
    by = {b["name"]: b["i"] for b in bones}
    up = model_space(bones, by["HookShot_Claw_Upper"])[:3, 3] - model_space(bones, by["HookShot_Claw_Bottom"])[:3, 3]
    right = model_space(bones, by["HookShot_Claw_R"])[:3, 3] - model_space(bones, by["HookShot_Claw_L"])[:3, 3]
    tip = model_space(bones, by["Tip_HookShot"])[:3, 3]
    # (the axes the placement assumes: refused if a game version moved them)
    assert up[1] < -.1 and abs(up[0]) < 1e-3 and abs(up[2]) < 1e-3, up
    assert right[2] > .1 and abs(right[0]) < 1e-3 and abs(right[1]) < 1e-3, right
    assert tip[0] < -.1 and abs(tip[1]) < 1e-3 and abs(tip[2]) < 1e-3, tip
    first = model_space(bones, m["matrix_to_bone"][0])
    out = ["// Generated by vr/tools/generate (hookshot.py) from your game's hookshot model and Link's skeletons.",
           "// Vertex buffer sizes and a few transforms only. Local file: do not commit or share.", "#pragma once",
           "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "/// The held hookshot's shapes (hookshot and longshot body, chain stub and hook): their vertex buffer sizes",
           "inline constexpr uint64_t hookshot_shapes[%d] = {%s};" % (len(m["shapes"]), ", ".join(
               "%d" % s["vb0"] for s in m["shapes"])),
           "inline constexpr unsigned hookshot_matrices = %d;   // (its palette: rigid matrices, 48 bytes each)" % m["nrigid"],
           "/// Its first palette matrix (%s) in the model: a draw's matrix 0 = the model's place x this" %
           bones[m["matrix_to_bone"][0]]["name"], row("hookshot_first", first),
           "/// Where the hookshot's origin sits in each wrist: the game's Weapon_L socket in the left, its mirror in the right"]
    for n, f in (("adult", ADULT), ("child", CHILD)):
        left = socket(models[f], np.eye(4))
        out += [row("hookshot_left_" + n, left), row("hookshot_right_" + n, mirrored(models[f], left))]
    chain = models[CHAIN]
    names = [chain["bones"][i]["name"] for i in chain["matrix_to_bone"]]
    assert names[0] == "Head" and names[1].startswith("SubLine_"), names[:2]   # (the hook's head: palette matrix 0)
    out += ["/// The fired chain (Item_Hookshot_Chain: the hook's head at its origin, the line behind it, every 0.383 m): its",
            "/// shapes' vertex buffer sizes and palette size; matrix 0 is the head",
            "inline constexpr uint64_t hookchain_shapes[%d] = {%s};" % (len(chain["shapes"]), ", ".join(
                "%d" % s["vb0"] for s in chain["shapes"])),
            "inline constexpr unsigned hookchain_matrices = %d;" % len(names)]
    out.append("} // namespace mkwvk::vr::rig")
    return "\n".join(out) + "\n"
