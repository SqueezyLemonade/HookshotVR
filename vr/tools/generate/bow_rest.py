"""vk_vr_bow_rest.h: the plain bow's 14 palette matrices at rest, relative to its root.

The VR bow is always drawn from this rest pose, whatever the game's own bow draw is doing (the game's ZR, held while the
VR bow is held, is also its draw); only the drawing hand bends the string. The rest is the bow's skeleton posed by the
game's own one-frame Weapon_Pose_Bow animation, with Maya scale (a bone does not inherit its parent's scale). This
matches what the game draws for the carried bow to within 0.0000002.
"""
import math

import numpy as np

from bfres_pose import still_pose
from models import BOW, BOW_ANIMATIONS, matrix

OUTPUT = "vk_vr_bow_rest.h"
INPUTS = (BOW, BOW_ANIMATIONS)
POSE = "Weapon_Pose_Bow"
SLOTS = 14


def rotation(x, y, z):
    cx, sx, cy, sy, cz, sz = math.cos(x), math.sin(x), math.cos(y), math.sin(y), math.cos(z), math.sin(z)
    return np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]) @ np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]) @ \
        np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]])


def rest_palette(bow, pose, relative=True):
    bones = bow["bones"]

    def srt(j):
        b = bones[j]
        s, r, t = pose.get(b["name"], (None, None, None))
        return np.array(s or b["scale"]), (r or b["rot"])[:3], np.array(t or b["pos"])

    def world(i):
        chain = []
        while i >= 0:
            chain.append(i)
            i = bones[i]["parent"]
        m, parent_scale = np.eye(4), np.ones(3)
        for j in reversed(chain):
            s, r, t = srt(j)
            local = np.eye(4)
            local[:3, :3] = np.diag(1 / parent_scale) @ rotation(*r) @ np.diag(s)
            local[:3, 3] = t
            m, parent_scale = m @ local, s
        return m
    # smooth slots: the bone's pose x its inverse bind; rigid slots: the bone's pose itself
    palette = [world(b) @ matrix(bow["inv_bind"][s]) if s < bow["nsmooth"] else world(b)
               for s, b in enumerate(bow["matrix_to_bone"])]
    if not relative:   # (in the model's own space: the slingshot's, slingshot.py)
        return palette
    root = np.linalg.inv(palette[0])
    return [root @ m for m in palette]


def make(models):
    bow = models[BOW]
    assert len(bow["matrix_to_bone"]) == SLOTS, len(bow["matrix_to_bone"])
    for b in bow["bones"]:
        assert b["flags"] & (1 << 12), "bow bone without Euler rotation: " + b["name"]
    rows = rest_palette(bow, still_pose(models.game.read(BOW_ANIMATIONS), POSE))
    out = ["// Generated by vr/tools/generate (bow_rest.py) from your game's bow model and its Weapon_Pose_Bow pose.",
           "// Local file: do not commit or share.", "#pragma once", "namespace mkwvk::vr::rig {",
           "inline constexpr float bow_rest[%d][12] = {" % SLOTS]
    out += ["    {" + ",".join("%.7ff" % (0.0 if abs(v) < 5e-8 else v) for v in m[:3].flat) + "}," for m in rows]
    out += ["};", "} // namespace mkwvk::vr::rig"]
    return "\n".join(out) + "\n"
