"""vk_vr_boomerang.h: child Link's Boomerang as the VR hand holds it.

The boomerang is one model (Item_Boomerang: Weapon_Boomerang's model), 5 shapes on 1 rigid matrix (Skl_Root, the
boomerang itself, 0.15 m from the model's origin; the model lies flat in its own x-z plane, its thickness along y). The
model's origin is on one wing, 10 cm from its tip, the wing running along the model's z: there the game holds it, as a
sword by its handle, on Link's left hand socket (Weapon_L). Not at the socket's bind pose: Link's own boomerang clips
(Boomerang_St, _Charge, _Catch; Player_Child_01) turn it 20 degrees and move it 1.6 cm, as his clips do the child's shield
mount (hand_sockets.py), so the socket is read from Boomerang_St, Link standing with it (headset 18 Nov: "it should be
gripped by its wing"). In the right hand its mirror image (hookshot.py mirrored), mirrored across its own thickness (y)
so its outline keeps its turn. Adult Link never holds it: his bind socket is kept for completeness.

Read from your game's files: the model's shape vertex buffer sizes (how its draws are recognised), its palette matrix's
rest place in the model (to find the model's origin in a draw), and both hands' sockets.
"""
import numpy as np

from arrows import model_space
from bfres_anim import animations
from hand_sockets import held_mount, socket
from hookshot import mirrored, row
from models import ADULT, CHILD, CHILD_ANIMATIONS

OUTPUT = "vk_vr_boomerang.h"
BOOMERANG = "Model/Item_Boomerang.Item_Boomerang.bfres.zs"
HOLD = "Boomerang_St"   # (Player_Child_01: Link standing with the boomerang in his left hand)
INPUTS = (BOOMERANG, ADULT, CHILD, CHILD_ANIMATIONS)


def make(models):
    m = models[BOOMERANG]
    assert m["nsmooth"] == 0 and m["nrigid"] == 1, (m["nsmooth"], m["nrigid"])
    bones = m["bones"]
    first = model_space(bones, m["matrix_to_bone"][0])
    # (the layout the placement assumes: refused if a game version changed it)
    assert abs(first[1, 3]) < 1e-3 and .05 < np.hypot(first[0, 3], first[2, 3]) < .4, first[:3, 3]
    out = ["// Generated by vr/tools/generate (boomerang.py) from your game's boomerang model and Link's skeletons.",
           "// Vertex buffer sizes and a few transforms only. Local file: do not commit or share.", "#pragma once",
           "#include <cstdint>", "namespace mkwvk::vr::rig {",
           "/// The held boomerang's shapes: their vertex buffer sizes",
           "inline constexpr uint64_t boomerang_shapes[%d] = {%s};" % (len(m["shapes"]), ", ".join(
               "%d" % s["vb0"] for s in m["shapes"])),
           "inline constexpr unsigned boomerang_matrices = %d;   // (its palette: rigid matrices, 48 bytes each)" % m["nrigid"],
           "/// Its palette matrix (%s) in the model: a draw's matrix 0 = the model's place x this" %
           bones[m["matrix_to_bone"][0]]["name"], row("boomerang_first", first),
           "/// Where the boomerang's origin sits in each wrist: the game's Weapon_L socket in the left, its mirror in the right"]
    clip = animations(models.game.read(CHILD_ANIMATIONS), [HOLD])[HOLD]
    child = models[CHILD]
    held = held_mount(child, clip, "Weapon_L")
    bind = next(b for b in child["bones"] if b["name"] == "Weapon_L")
    # (the held mount near the bind one, a turn of the same socket: refused if a game version moved it elsewhere)
    assert np.linalg.norm(np.subtract(held["pos"], bind["pos"])) < .04, (held["pos"], bind["pos"])
    for n, f in (("adult", ADULT), ("child", CHILD)):
        left = socket(models[f], np.eye(4), mount=held if n == "child" else None)
        out += [row("boomerang_left_" + n, left),
                row("boomerang_right_" + n, mirrored(models[f], left, np.diag([1.0, -1, 1, 1])))]
    out.append("} // namespace mkwvk::vr::rig")
    return "\n".join(out) + "\n"
