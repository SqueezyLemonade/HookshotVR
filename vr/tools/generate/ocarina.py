"""vk_vr_ocarina.h: the ocarina and its holder, as first person puts them on the VR belt (vr/items/ocarina/held_ocarina.inc).

Link carries his ocarina at the back of his belt from the moment he owns one: a holder (Item_OcarinaHolder_Fairy or
_Time: a pouch with a band of belt leather round it, 2 smooth matrices, Skl_Root and Body) with the ocarina in it
(Item_Ocarina_Fairy or _Time: one rigid matrix, its Skl_Root, so its palette is its place in the world). Which ones are
drawn is the game's choice (none, the Fairy Ocarina or the Ocarina of Time): the renderer recognises each by its draws.

Read from your game's models: their shapes' vertex buffer sizes (how their draws are recognised) and their palette
sizes. A model your game does not have is left out (nothing of it is recognised).
"""
OUTPUT = "vk_vr_ocarina.h"
INPUTS = ()   # (every model is optional: checked below)
OCARINAS = ("Item_Ocarina_Fairy.Item_Ocarina_Fairy", "Item_Ocarina_Time.Item_Ocarina_Time")
HOLDERS = ("Item_OcarinaHolder_Fairy.Item_OcarinaHolder_Fairy", "Item_OcarinaHolder_Time.Item_OcarinaHolder_Time")


def shapes(models, names, matrices):
    """The vertex buffer sizes of these models' shapes, each model's palette asserted to be `matrices` long"""
    out, found = [], []
    for name in names:
        rel = "Model/%s.bfres.zs" % name
        if not models.game.exists(rel):
            continue
        m = models[rel]
        assert m["nsmooth"] + m["nrigid"] == matrices, "%s: %d palette matrices, not %d" % (
            name, m["nsmooth"] + m["nrigid"], matrices)
        found.append(name.split(".")[1])
        out += [s["vb0"] for s in m["shapes"] if s["vb0"] not in out]
    return sorted(out), found


def make(models):
    ocarinas, have_ocarinas = shapes(models, OCARINAS, 1)
    holders, have_holders = shapes(models, HOLDERS, 2)
    table = lambda name, v: "inline constexpr uint64_t %s[%d] = {%s};" % (name, max(1, len(v)),
                                                                           ", ".join(map(str, v)) or "0")
    out = ["// Generated by vr/tools/generate (ocarina.py) from your game's ocarina and holder models.",
           "// Vertex buffer sizes only. Local file: do not commit or share.", "#pragma once", "#include <cstdint>",
           "namespace mkwvk::vr::rig {",
           "/// The ocarinas (%s): one rigid matrix, the model's place" % (", ".join(have_ocarinas) or "none in your game"),
           "inline constexpr unsigned ocarina_matrices = 1;", table("ocarina_shapes", ocarinas),
           "/// Their holders on the belt (%s): two smooth matrices, matrix 0 the model's place" % (
               ", ".join(have_holders) or "none in your game"),
           "inline constexpr unsigned ocarina_holder_matrices = 2;", table("ocarina_holder_shapes", holders),
           "} // namespace mkwvk::vr::rig"]
    return "\n".join(out) + "\n"
