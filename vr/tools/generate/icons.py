"""vk_vr_icons.h: the item icons the VR radial menus show (vr/menu/radial) and the wrist HUD's, from your game's own UI icons.

Each icon is UI/Tex/Icon/<name>.bntx.zs: one ASTC 4x4 texture (sRGB), 341 or 683 pixels square, in the Switch's
block-linear layout. Unswizzled here (the same layout as bow_reticle.py's, for 16-byte blocks), decoded with
texture2ddecoder (in the builder's Python), shrunk to SIZE pixels and stored premultiplied, sRGB, RGBA.
Can also save a PNG sheet for checking: python icons.py <romfs> preview.png
"""
import struct
import sys

OUTPUT = "vk_vr_icons.h"
SIZE = 96
# (icon name: the icon file's; the radial menus refer to icons by these names, vr/menu/radial_items.h)
ICONS = ("Item_DekuStick", "Item_DekuNut", "Item_Bomb", "Item_Boomerang", "Weapon_Range_SlingShot", "Item_Hookshot",
         "Item_Longshot", "Item_Hammer", "Armor_GlassTruth", "Item_Bombchu", "Item_DinFire", "Item_FaroreWind",
         "Item_NayruLove", "Item_MagicBean", "Armor_Adult_HeavyBoot", "Armor_Adult_HoverBoot", "Weapon_Range_Bow",
         "Pouch_Range_BowAndArrow_Fire", "Pouch_Range_BowAndArrow_Ice", "Pouch_Range_BowAndArrow_Light",
         "Weapon_Sword_Kokiri", "Weapon_Sword_Master", "Weapon_Sword_Biggoron", "Weapon_Sword_Giant",
         "Weapon_Sword_BrokenGiant", "Weapon_Shield_Deku",
         "Weapon_Shield_Hylian", "Weapon_Shield_Mirror", "Armor_Adult_Normal", "Armor_Adult_Goron", "Armor_Adult_Zora",
         "Item_Ocarina_Fairy", "Item_Ocarina_Time",
         "Item_Bottle", "Item_Bottle_RedPotion", "Item_Bottle_GreenPotion", "Item_Bottle_BluePotion", "Item_Bottle_BlueFire",
         "Item_Bottle_Fish", "Item_Bottle_Letter", "Item_Bottle_BigPoe", "Item_Bottle_Poe", "Item_Bottle_Bug",
         "Item_Bottle_Fairy", "Item_Bottle_Milk", "Item_Bottle_HalfMilk",
         # (the wrist check HUD's, vr/menu/wrist_draw.inc: the rupee by the wallet, the dungeon's keys, map and compass)
         "Obj_Rupee_Green", "Obj_Rupee_Blue", "Obj_Rupee_Red", "Item_Dungeon_SmallKey", "Item_Dungeon_BossKey",
         "Item_Dungeon_Map", "Item_Dungeon_Compass")
INPUTS = tuple("UI/Tex/Icon/%s.bntx.zs" % n for n in ICONS)
ASTC_4X4 = 0x2d   # (the format's upper byte; the lower is its kind, 6: sRGB)


def texture(d):
    """the BNTX file's one texture: (width, height, block height log2, its data)"""
    p = d.find(b"BRTI")
    assert p >= 0
    fmt = struct.unpack_from("<I", d, p + 0x1c)[0]
    assert fmt >> 8 == ASTC_4X4, hex(fmt)
    w, h = struct.unpack_from("<II", d, p + 0x24)
    th = struct.unpack_from("<I", d, p + 0x34)[0] & 7
    table = struct.unpack_from("<Q", d, p + 0x70)[0]
    start = struct.unpack_from("<Q", d, table)[0]
    return w, h, th, d, start


def unswizzle(w, h, th, d, start, bpe=16):
    """block-linear blocks (bpe bytes each, 4x4 pixels) in plain row order"""
    bw, bh = (w + 3) // 4, (h + 3) // 4
    gobs = (bw * bpe + 63) // 64
    out = bytearray(bw * bh * bpe)
    for by in range(bh):
        for bx in range(bw):
            for i in range(0, bpe, 16):
                x = bx * bpe + i
                gob = ((x & 63) >> 5) * 256 + ((by & 7) >> 2) * 128 + ((x & 31) >> 4) * 64 + ((by >> 1) & 1) * 32 + \
                      (by & 1) * 16
                off = (by >> (3 + th)) * gobs * (512 << th) + (x >> 6) * (512 << th) + ((by >> 3) & ((1 << th) - 1)) * 512 + gob
                o = (by * bw + bx) * bpe + i
                out[o:o + 16] = d[start + off:start + off + 16]
    return bytes(out)


def icon(d):
    """the icon as SIZE x SIZE premultiplied RGBA bytes"""
    import texture2ddecoder
    from PIL import Image
    w, h, th, data, start = texture(d)
    bgra = texture2ddecoder.decode_astc(unswizzle(w, h, th, data, start), w, h, 4, 4)
    image = Image.frombytes("RGBA", (w, h), bgra, "raw", "BGRA").resize((SIZE, SIZE), Image.LANCZOS)
    px = bytearray(image.tobytes())
    for i in range(0, len(px), 4):
        a = px[i + 3]
        px[i], px[i + 1], px[i + 2] = px[i] * a // 255, px[i + 1] * a // 255, px[i + 2] * a // 255
    return bytes(px)


def make(models):
    game = models.game
    out = ["// Generated by vr/tools/generate (icons.py) from your game's item icons.",
           "// Local file: do not commit or share.", "#pragma once", "namespace mkwvk::vr::art {",
           "inline constexpr int icon_size = %d;   // (pixels square: premultiplied sRGB RGBA, rows top first)" % SIZE,
           "struct Icon { const char* name; const unsigned char* rgba; };"]
    names = []
    for n in ICONS:
        rel = "UI/Tex/Icon/%s.bntx.zs" % n
        if not game.exists(rel):
            continue
        px = icon(game.read(rel))
        out.append("inline constexpr unsigned char icon_%s[] =" % n)
        for row in range(0, len(px), 1024):
            out.append('    "' + "".join("\\%03o" % b for b in px[row:row + 1024]) + '"')
        out[-1] += ";"
        names.append(n)
    out.append("inline constexpr Icon icons[%d] = {%s};" % (len(names), ", ".join('{"%s", icon_%s}' % (n, n) for n in names)))
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    from game_files import GameFiles
    from PIL import Image
    game = GameFiles(sys.argv[1])
    sheet = Image.new("RGBA", (SIZE * 8, SIZE * ((len(ICONS) + 7) // 8)), (40, 40, 40, 255))
    for k, n in enumerate(ICONS):
        rel = "UI/Tex/Icon/%s.bntx.zs" % n
        if game.exists(rel):
            img = Image.frombytes("RGBA", (SIZE, SIZE), icon(game.read(rel)))
            sheet.alpha_composite(img, ((k % 8) * SIZE, (k // 8) * SIZE))
    sheet.save(sys.argv[2])
